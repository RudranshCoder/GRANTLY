/**
 * Get a single scholarship by its unique ID.
 */
export function getScholarshipById(id: string): Scholarship | undefined {
  return scholarships.find(s => s.id === id);
}

/**
 * Filter scholarships matching a specific category.
 * Case-insensitive match against ScholarshipCategory.
 */
export function getScholarshipsByCategory(category: string): Scholarship[] {
  const targetCategory = category.toLowerCase().trim();
  return scholarships.filter(s =>
    s.category.some(cat => cat.toLowerCase() === targetCategory)
  );
}

/**
 * Filter scholarships matching a specific education level.
 * Case-insensitive match against EducationLevel.
 */
export function getScholarshipsByEducationLevel(level: string): Scholarship[] {
  const targetLevel = level.toLowerCase().trim();
  return scholarships.filter(s =>
    s.educationLevel.some(lvl => lvl.toLowerCase() === targetLevel)
  );
}

/**
 * Search scholarships across title, provider, description, shortDescription, and tags.
 */
export function searchScholarships(query: string): Scholarship[] {
  const q = query.toLowerCase().trim();
  if (!q) return scholarships;

  return scholarships.filter(s => {
    return (
      s.title.toLowerCase().includes(q) ||
      s.provider.toLowerCase().includes(q) ||
      s.description.toLowerCase().includes(q) ||
      s.shortDescription.toLowerCase().includes(q) ||
      s.state.toLowerCase().includes(q) ||
      s.tags.some(tag => tag.toLowerCase().includes(q))
    );
  });
}

/**
 * Get scholarships whose deadline falls within the specified number of days from now.
 * Results are sorted in ascending order of deadline (soonest first).
 */
export function getUpcomingDeadlines(days: number = 30): Scholarship[] {
  const now = new Date();
  const futureLimit = new Date(now.getTime() + days * 24 * 60 * 60 * 1000);

  return scholarships
    .filter(s => {
      const deadlineDate = new Date(s.deadline);
      return deadlineDate >= now && deadlineDate <= futureLimit;
    })
    .sort((a, b) => new Date(a.deadline).getTime() - new Date(b.deadline).getTime());
}
